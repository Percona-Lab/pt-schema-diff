package schemadiff

// Comparing every database of two servers: one ReportInput per database, plus the databases that exist on one side
// only, and a combined migration script with a USE line per database.

import (
	"context"
	"encoding/json"
	"fmt"
	"html"
	"strings"
)

// Database statuses in a multi-database comparison.
const (
	DBIdentical  = "identical"
	DBDiffers    = "differs"
	DBOnlySource = "only_source" // created by the script
	DBOnlyTarget = "only_target" // reported; dropping it is left to you
	DBError      = "error"
)

var dbStatusText = map[string]string{DBIdentical: "identical", DBDiffers: "differs",
	DBOnlySource: "only on the source · create", DBOnlyTarget: "only on the target", DBError: "error"}

// DatabaseReport is the comparison of one database.
type DatabaseReport struct {
	Name           string
	Status         string
	Error          string
	CreateDatabase string // for DBOnlySource: CREATE DATABASE IF NOT EXISTS ... from the source
	Input          ReportInput
}

// MultiReport is the comparison of every database of two servers.
type MultiReport struct {
	SourceLabel  string
	TargetLabel  string
	Databases    []DatabaseReport
	IncludeDrops bool
	ShowSame     bool
	Title        string
	Tool         string
}

// MultiCounts summarizes a multi-database comparison.
type MultiCounts struct {
	Databases  int `json:"databases"`
	Identical  int `json:"identical"`
	Differ     int `json:"differ"`
	OnlySource int `json:"only_source"`
	OnlyTarget int `json:"only_target"`
	Errors     int `json:"errors"`
	Counts         // changes over all databases
}

// Summary counts databases by status and changes by severity.
func (m MultiReport) Summary() MultiCounts {
	c := MultiCounts{Databases: len(m.Databases)}
	for _, d := range m.Databases {
		switch d.Status {
		case DBIdentical:
			c.Identical++
		case DBDiffers:
			c.Differ++
		case DBOnlySource:
			c.OnlySource++
		case DBOnlyTarget:
			c.OnlyTarget++
		default:
			c.Errors++
		}
		if d.Status == DBDiffers || d.Status == DBOnlySource {
			s := d.Input.Result.Summary()
			c.Tables += s.Tables
			c.Create += s.Create
			c.Drop += s.Drop
			c.Alter += s.Alter
			c.Same += s.Same
			c.Critical += s.Critical
			c.Warning += s.Warning
			c.Suggestion += s.Suggestion
			c.OK += s.OK
		}
	}
	return c
}

// HasDifferences is true when any database differs or exists on one side only.
func (m MultiReport) HasDifferences() bool {
	c := m.Summary()
	return c.Differ+c.OnlySource+c.OnlyTarget > 0
}

func (m MultiReport) summaryLine() string {
	c := m.Summary()
	return fmt.Sprintf("%d databases: %d identical, %d differ, %d only on the source, %d only on the target, %d errors. "+
		"Changes: %d critical, %d warnings, %d suggestions, %d safe.",
		c.Databases, c.Identical, c.Differ, c.OnlySource, c.OnlyTarget, c.Errors, c.Critical, c.Warning, c.Suggestion, c.OK)
}

func (d DatabaseReport) detail() string {
	switch d.Status {
	case DBDiffers, DBOnlySource:
		s := d.Input.Result.Summary()
		return fmt.Sprintf("%d to create, %d to change, %d only in the target; %d critical, %d warnings",
			s.Create, s.Alter, s.Drop, s.Critical, s.Warning)
	case DBError:
		return d.Error
	case DBOnlyTarget:
		return "not dropped by the script"
	}
	return ""
}

// Script is the combined migration script: one section with a USE line per database that needs changes.
func (m MultiReport) Script() string {
	tool := orDefault(m.Tool, "pt-schema-diff")
	lines := []string{
		fmt.Sprintf("-- Schema migration generated by %s, %s", tool, Now().Format("2006-01-02 15:04")),
		"-- Makes: " + m.TargetLabel, "-- match:  " + m.SourceLabel,
		"-- Review every statement and test on a copy first. Run during low traffic: some ALTERs copy",
		"-- their table and block writes to it while they run (see the report for which ones).", ""}
	excluded, any := false, false
	var body []string
	for _, d := range m.Databases {
		switch d.Status {
		case DBDiffers, DBOnlySource:
			part := d.Input.Result.MigrationScript(ScriptOptions{IncludeDrops: m.IncludeDrops, Database: d.Name, BodyOnly: true})
			if part == "" && d.Status != DBOnlySource {
				continue
			}
			any = true
			excluded = excluded || d.Input.Result.HasExcluded(m.IncludeDrops)
			body = append(body, fmt.Sprintf("-- ============================== Database %s ==============================", Quote(d.Name)), "")
			if d.Status == DBOnlySource {
				body = append(body, "-- It exists only on the source.", d.CreateDatabase+";", "")
			}
			if part != "" {
				body = append(body, strings.TrimRight(part, "\n"), "")
			}
		case DBOnlyTarget:
			any = true
			body = append(body, fmt.Sprintf("-- ============================== Database %s ==============================", Quote(d.Name)), "",
				"-- It exists only on the target. Dropping a whole database is never scripted; if you mean it:",
				"-- DROP DATABASE "+Quote(d.Name)+";", "")
		}
	}
	if !any {
		return strings.Join(append(lines, "-- The schemas match: nothing to change."), "\n") + "\n"
	}
	if excluded {
		lines = append(lines, "-- Statements that delete data (DROP TABLE, DROP COLUMN) are commented out. Run with",
			"-- --include-drops to include them.", "")
	}
	return strings.TrimRight(strings.Join(append(lines, body...), "\n"), " \n") + "\n"
}

func (m MultiReport) shown() []DatabaseReport {
	var out []DatabaseReport
	for _, d := range m.Databases {
		if d.Status != DBIdentical || m.ShowSame {
			out = append(out, d)
		}
	}
	return out
}

// MultiTextReport is the multi-database report for a terminal.
func MultiTextReport(m MultiReport) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Source: %s (the schemas to match)\n# Target: %s (the schemas the script changes)\n# %s\n\n",
		m.SourceLabel, m.TargetLabel, m.summaryLine())
	width := len("DATABASE")
	for _, d := range m.Databases {
		width = max(width, len(d.Name))
	}
	fmt.Fprintf(&b, "%-*s  %-28s %s\n", width, "DATABASE", "STATUS", "DETAILS")
	for _, d := range m.Databases {
		fmt.Fprintf(&b, "%-*s  %-28s %s\n", width, d.Name, dbStatusText[d.Status], d.detail())
	}
	for _, d := range m.shown() {
		if d.Status == DBOnlyTarget || d.Status == DBError {
			continue
		}
		fmt.Fprintf(&b, "\n######## Database %s — %s ########\n", Quote(d.Name), dbStatusText[d.Status])
		in := d.Input
		in.Script = ""
		b.WriteString(TextReport(in))
	}
	b.WriteString("\n" + m.Script())
	return b.String()
}

// MultiMarkdownReport is the multi-database report as Markdown.
func MultiMarkdownReport(m MultiReport) string {
	out := []string{"# " + orDefault(m.Title, "Schema diff"), "",
		"- **Source** (the schemas to match): " + m.SourceLabel,
		"- **Target** (the schemas the script changes): " + m.TargetLabel,
		"- **Generated:** " + Now().Format("2006-01-02 15:04"), "", m.summaryLine(), "",
		"| Database | Status | Details |", "|---|---|---|"}
	for _, d := range m.Databases {
		out = append(out, fmt.Sprintf("| `%s` | %s | %s |", d.Name, dbStatusText[d.Status], strings.ReplaceAll(d.detail(), "|", "\\|")))
	}
	out = append(out, "")
	for _, d := range m.shown() {
		if d.Status == DBOnlyTarget || d.Status == DBError {
			continue
		}
		in := d.Input
		in.Script = ""
		in.Title = fmt.Sprintf("Database `%s` — %s", d.Name, dbStatusText[d.Status])
		// One level down: the database is a section of the whole report.
		section := strings.ReplaceAll("\n"+MarkdownReport(in), "\n#", "\n##")
		out = append(out, strings.TrimLeft(section, "\n"))
	}
	out = append(out, "# Migration script", "", "```sql", strings.TrimRight(m.Script(), "\n"), "```", "")
	return strings.Join(out, "\n")
}

// MultiHTMLReport is the multi-database report as one HTML page.
func MultiHTMLReport(m MultiReport) string {
	esc := html.EscapeString
	c := m.Summary()
	title := orDefault(m.Title, "Schema Diff Report")
	var b strings.Builder
	b.WriteString(htmlOpen(title, fmt.Sprintf("Makes %s match %s", m.TargetLabel, m.SourceLabel)))
	b.WriteString(htmlKPIs([][2]any{{c.Critical, "CRITICAL (DATA LOSS)"}, {c.Warning, "WARNINGS"}, {c.Differ, "DATABASES THAT DIFFER"},
		{c.OnlySource + c.OnlyTarget, "ON ONE SIDE ONLY"}, {c.Identical, "IDENTICAL DATABASES"}}))
	b.WriteString("<h2>Comparison</h2>" + htmlFacts([][2]string{
		{"Source (the schemas to match)", m.SourceLabel},
		{"Target (the schemas the script changes)", m.TargetLabel},
		{"Databases compared", fmt.Sprintf("%d: %d identical, %d differ, %d only on the source, %d only on the target, %d errors",
			c.Databases, c.Identical, c.Differ, c.OnlySource, c.OnlyTarget, c.Errors)},
		{"Statements that delete data", dropsText(m.IncludeDrops)},
	}) + htmlLegend())
	b.WriteString(`<h2>Databases</h2><table class="grid"><tr><th>Database</th><th>Status</th><th>Details</th></tr>`)
	for _, d := range m.Databases {
		name := esc(d.Name)
		if d.Status == DBDiffers || d.Status == DBOnlySource {
			name = fmt.Sprintf(`<a href="#db-%s">%s</a>`, esc(d.Name), name)
		}
		fmt.Fprintf(&b, "<tr><td><b>%s</b></td><td>%s</td><td>%s</td></tr>", name, esc(dbStatusText[d.Status]), esc(d.detail()))
	}
	b.WriteString("</table>")
	for _, d := range m.shown() {
		if d.Status == DBOnlyTarget || d.Status == DBError {
			continue
		}
		fmt.Fprintf(&b, `<h2 id="db-%s">Database %s · %s</h2><p class="muted">%s</p>`, esc(d.Name), esc(d.Name),
			esc(dbStatusText[d.Status]), esc(d.Input.summaryLine()))
		if d.Input.Verify != nil {
			b.WriteString(`<p class="muted">Script test: ` + esc(d.Input.Verify.Text()) + "</p>")
		}
		b.WriteString(htmlVerify(d.Input.Verify))
		b.WriteString(htmlTables(d.Input, "h3", "h3"))
	}
	b.WriteString(htmlScript(m.Script()))
	return b.String() + htmlClose
}

// MultiJSONReport is the multi-database report as JSON.
func MultiJSONReport(m MultiReport) ([]byte, error) {
	type db struct {
		Name   string          `json:"name"`
		Status string          `json:"status"`
		Error  string          `json:"error,omitempty"`
		Report json.RawMessage `json:"report,omitempty"`
	}
	var dbs []db
	for _, d := range m.Databases {
		e := db{Name: d.Name, Status: d.Status, Error: d.Error}
		if d.Status == DBDiffers || d.Status == DBOnlySource || d.Status == DBIdentical {
			raw, err := JSONReport(d.Input)
			if err != nil {
				return nil, err
			}
			e.Report = raw
		}
		dbs = append(dbs, e)
	}
	if dbs == nil {
		dbs = []db{}
	}
	return json.MarshalIndent(map[string]any{
		"source":        m.SourceLabel,
		"target":        m.TargetLabel,
		"generated":     Now().Format("2006-01-02T15:04:05"),
		"summary":       m.Summary(),
		"differences":   m.HasDifferences(),
		"include_drops": m.IncludeDrops,
		"databases":     dbs,
		"script":        m.Script(),
	}, "", "  ")
}

// CreateDatabaseStatement is SHOW CREATE DATABASE, made idempotent (CREATE DATABASE IF NOT EXISTS).
func CreateDatabaseStatement(ctx context.Context, db Queryer, name string) (string, error) {
	var n, stmt string
	if err := db.QueryRowContext(ctx, "SHOW CREATE DATABASE "+Quote(name)).Scan(&n, &stmt); err != nil {
		return "", err
	}
	if !strings.Contains(strings.ToUpper(stmt), "IF NOT EXISTS") {
		stmt = strings.Replace(stmt, "CREATE DATABASE ", "CREATE DATABASE IF NOT EXISTS ", 1)
	}
	return stmt, nil
}
