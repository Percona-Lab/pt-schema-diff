package schemadiff

// The migration script: the statements that make the target match the source, in an order that always works.

import (
	"fmt"
	"regexp"
	"strings"
	"time"
)

// Now is the clock used for timestamps in scripts and reports (replaceable in tests).
var Now = time.Now

// Statement is one statement of the migration script. Statements that are not Included (they delete data and drops
// were not asked for) are written as comments.
type Statement struct {
	Phase    string `json:"phase"`
	SQL      string `json:"sql"`
	Included bool   `json:"included"`
}

// Phases lists the script phases, in the order they run, with their heading in the script.
var Phases = [][2]string{
	{PhaseDropFK, "Drop foreign keys that change or go away (first, so their indexes and columns can change)"},
	{PhaseCreate, "Create the tables that exist only in the source"},
	{PhaseAlter, "Change existing tables"},
	{PhaseDrop, "Drop the tables that exist only in the target"},
	{PhaseAddFK, "Add foreign keys (last, so the tables and indexes they need exist)"},
}

func alterSQL(table string, clauses []string) string {
	return "ALTER TABLE " + Quote(table) + "\n  " + strings.Join(clauses, ",\n  ") + ";"
}

// TableStatements returns the statements for one table. Clauses that delete data are excluded unless includeDrops.
func TableStatements(e TableDiff, includeDrops bool) []Statement {
	byPhase := map[string][]Change{}
	for _, c := range e.Changes {
		if c.Clause != "" {
			byPhase[c.Phase] = append(byPhase[c.Phase], c)
		}
	}
	clauses := func(cs []Change) []string {
		out := make([]string, len(cs))
		for i, c := range cs {
			out[i] = c.Clause
		}
		return out
	}
	var out []Statement
	if cs := byPhase[PhaseDropFK]; len(cs) > 0 {
		out = append(out, Statement{PhaseDropFK, alterSQL(e.Name, clauses(cs)), true})
	}
	for _, c := range byPhase[PhaseCreate] {
		out = append(out, Statement{PhaseCreate, c.Clause + ";", true})
	}
	var kept, leftOut []string
	for _, c := range byPhase[PhaseAlter] {
		if includeDrops || !c.DataLoss {
			kept = append(kept, c.Clause)
		} else {
			leftOut = append(leftOut, c.Clause)
		}
	}
	if len(kept) > 0 {
		out = append(out, Statement{PhaseAlter, alterSQL(e.Name, kept), true})
	}
	if len(leftOut) > 0 {
		out = append(out, Statement{PhaseAlter, alterSQL(e.Name, leftOut), false})
	}
	for _, c := range byPhase[PhaseDrop] {
		out = append(out, Statement{PhaseDrop, c.Clause + ";", includeDrops})
	}
	if cs := byPhase[PhaseAddFK]; len(cs) > 0 {
		out = append(out, Statement{PhaseAddFK, alterSQL(e.Name, clauses(cs)), true})
	}
	return out
}

// Commented turns SQL into SQL comment lines.
func Commented(sql string) string {
	lines := strings.Split(sql, "\n")
	for i, l := range lines {
		lines[i] = "-- " + l
	}
	return strings.Join(lines, "\n")
}

// ScriptOptions controls the migration script.
type ScriptOptions struct {
	IncludeDrops bool
	Database     string // for the USE line; empty for none
	SourceLabel  string
	TargetLabel  string
	Tool         string // name in the header line
	// BodyOnly leaves out the header comments and returns "" when there is nothing to change (for one database of
	// a multi-database script).
	BodyOnly bool
}

func (r Result) allStatements(includeDrops bool) []Statement {
	var out []Statement
	for _, t := range r.Tables {
		out = append(out, TableStatements(t, includeDrops)...)
	}
	return out
}

// MigrationScript writes the whole migration as one SQL script. Excluded statements are kept as comments.
func (r Result) MigrationScript(o ScriptOptions) string {
	statements := r.allStatements(o.IncludeDrops)
	tool, src, tgt := o.Tool, o.SourceLabel, o.TargetLabel
	if tool == "" {
		tool = "pt-schema-diff"
	}
	if src == "" {
		src = "source"
	}
	if tgt == "" {
		tgt = "target"
	}
	lines := []string{
		fmt.Sprintf("-- Schema migration generated by %s, %s", tool, Now().Format("2006-01-02 15:04")),
		"-- Makes: " + tgt, "-- match:  " + src,
		"-- Review every statement and test on a copy first. Run during low traffic: some ALTERs copy",
		"-- their table and block writes to it while they run (see the report for which ones).", ""}
	if o.BodyOnly {
		if len(statements) == 0 {
			return ""
		}
		lines = nil
	}
	if len(statements) == 0 {
		return strings.Join(append(lines, "-- The schemas match: nothing to change."), "\n") + "\n"
	}
	for _, s := range statements {
		if !s.Included && !o.BodyOnly {
			lines = append(lines, "-- Statements that delete data (DROP TABLE, DROP COLUMN) are commented out. Run with",
				"-- --include-drops to include them.", "")
			break
		}
	}
	if o.Database != "" {
		lines = append(lines, "USE "+Quote(o.Database)+";", "")
	}
	for _, ph := range Phases {
		var block []Statement
		for _, s := range statements {
			if s.Phase == ph[0] {
				block = append(block, s)
			}
		}
		if len(block) == 0 {
			continue
		}
		lines = append(lines, "-- "+ph[1], "")
		for _, s := range block {
			if s.Included {
				lines = append(lines, s.SQL, "")
			} else {
				lines = append(lines, Commented(s.SQL), "")
			}
		}
	}
	return strings.TrimRight(strings.Join(lines, "\n"), " \n") + "\n"
}

// ExecutableStatements returns the statements the script runs, in order.
func (r Result) ExecutableStatements(includeDrops bool) []string {
	statements := r.allStatements(includeDrops)
	var out []string
	for _, ph := range Phases {
		for _, s := range statements {
			if s.Phase == ph[0] && s.Included {
				out = append(out, s.SQL)
			}
		}
	}
	return out
}

var (
	reQuotedQualified   = regexp.MustCompile("`(?:[^`]|``)+`\\s*\\.\\s*`")
	reUnquotedQualified = regexp.MustCompile("[A-Za-z_$][\\w$]*\\s*\\.\\s*[`A-Za-z_$]")
)

// NamesOtherDatabase is true when a statement names a table as `db`.`table` (outside string literals).
func NamesOtherDatabase(stmt string) bool {
	masked, _ := protect(stmt, reTextLiteral)
	if reQuotedQualified.MatchString(masked) {
		return true
	}
	for i := 0; i < len(masked); {
		loc := reUnquotedQualified.FindStringIndex(masked[i:])
		if loc == nil {
			return false
		}
		start := i + loc[0]
		if start == 0 || !strings.ContainsRune("$.`", rune(masked[start-1])) && !isWordByte(masked[start-1]) {
			return true
		}
		i = start + 1
	}
	return false
}

func isWordByte(b byte) bool {
	return b == '_' || b >= '0' && b <= '9' || b >= 'a' && b <= 'z' || b >= 'A' && b <= 'Z' || b >= 0x80
}

// OnlineSchemaChangeCommand is a pt-online-schema-change command for a table's ALTER (without the foreign key
// phases), or "" when the table has no ALTER.
func OnlineSchemaChangeCommand(e TableDiff, database string) string {
	var clauses []string
	for _, c := range e.Changes {
		if c.Clause != "" && c.Phase == PhaseAlter {
			clauses = append(clauses, strings.Join(strings.Fields(c.Clause), " "))
		}
	}
	if len(clauses) == 0 {
		return ""
	}
	alter := strings.ReplaceAll(strings.Join(clauses, ", "), "'", `'"'"'`) // single-quoted for the shell
	target := "t=" + e.Name
	if database != "" {
		target = "D=" + database + ",t=" + e.Name
	}
	return fmt.Sprintf("pt-online-schema-change --alter '%s' \\\n  %s --dry-run\n"+
		"# then the same command with --execute instead of --dry-run", alter, target)
}

// DDLDiff is a unified diff of the target and source CREATE TABLE text of a table.
func DDLDiff(e TableDiff) string {
	lines := func(t *Table) []string {
		if t == nil {
			return nil
		}
		return strings.Split(CreateStatement(t, true), "\n")
	}
	return UnifiedDiff(lines(e.Target), lines(e.Source), "target", "source", 2)
}

// HasExcluded is true when the script leaves statements that delete data commented out.
func (r Result) HasExcluded(includeDrops bool) bool {
	for _, s := range r.allStatements(includeDrops) {
		if !s.Included {
			return true
		}
	}
	return false
}
